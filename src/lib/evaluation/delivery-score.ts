import type { DeliveryStats } from '@/lib/speech/transcript'
import type { EvaluationFlag } from '@/lib/evaluation/types'

/**
 * §16 — delivery is pure arithmetic over DeliveryStats. No AI is involved.
 * Every band's lower bound is inclusive and its upper bound exclusive.
 */

export const DELIVERY_WEIGHTS = { pace: 0.25, fillers: 0.3, pauses: 0.25, silence: 0.2 } as const

/** Preconditions: rates are meaningless on a very short clip or an unreliable transcript. */
export const MIN_AUDIO_CONFIDENCE = 0.6
export const MIN_DELIVERY_DURATION_SEC = 20
export const MIN_DELIVERY_WORDS = 30

export function paceScore(wpm: number): number {
  if (wpm >= 120 && wpm < 161) return 100
  if ((wpm >= 100 && wpm < 120) || (wpm >= 161 && wpm < 181)) return 75
  if ((wpm >= 80 && wpm < 100) || (wpm >= 181 && wpm < 201)) return 50
  return 25
}

export function fillersScore(perMinute: number): number {
  if (perMinute < 2) return 100
  if (perMinute < 4) return 75
  if (perMinute < 6) return 50
  if (perMinute < 8) return 30
  return 10
}

export function pausesScore(longestSec: number): number {
  if (longestSec < 2) return 100
  if (longestSec < 4) return 80
  if (longestSec < 6) return 55
  if (longestSec < 10) return 30
  return 10
}

export function silenceScore(ratio: number): number {
  if (ratio < 0.15) return 100
  if (ratio < 0.25) return 85
  if (ratio < 0.35) return 65
  if (ratio < 0.5) return 40
  return 20
}

export type DeliveryBreakdown = {
  pace: number
  fillers: number
  pauses: number
  silence: number
}

export function deliveryBreakdown(stats: DeliveryStats): DeliveryBreakdown {
  return {
    pace: paceScore(stats.wordsPerMinute),
    fillers: fillersScore(stats.disfluencies.perMinute),
    pauses: pausesScore(stats.pauses.longestSec),
    silence: silenceScore(stats.silenceRatio),
  }
}

/** Unrounded weighted delivery score. Rounding happens once, at the end (§18). */
export function deliveryScoreRaw(stats: DeliveryStats): number {
  const b = deliveryBreakdown(stats)
  return (
    b.pace * DELIVERY_WEIGHTS.pace +
    b.fillers * DELIVERY_WEIGHTS.fillers +
    b.pauses * DELIVERY_WEIGHTS.pauses +
    b.silence * DELIVERY_WEIGHTS.silence
  )
}

export type DeliveryEvaluation =
  | { scorable: true; score: number; breakdown: DeliveryBreakdown; tips: string[] }
  | { scorable: false; flag: EvaluationFlag | null; reason: string }

export function evaluateDelivery(input: {
  inputMode?: string | null
  delivery?: DeliveryStats | null
  audioConfidence?: number | null
}): DeliveryEvaluation {
  if (input.inputMode !== 'spoken' || !input.delivery) {
    return { scorable: false, flag: null, reason: 'Answer was not spoken.' }
  }
  if (typeof input.audioConfidence === 'number' && input.audioConfidence < MIN_AUDIO_CONFIDENCE) {
    return {
      scorable: false,
      flag: 'low_audio_confidence',
      reason: 'Audio quality was too poor to analyse delivery reliably.',
    }
  }
  const stats = input.delivery
  if (stats.durationSec < MIN_DELIVERY_DURATION_SEC || stats.wordCount < MIN_DELIVERY_WORDS) {
    return {
      scorable: false,
      flag: 'delivery_too_short',
      reason: 'The recording was too short to measure pace and fluency.',
    }
  }
  return {
    scorable: true,
    score: Math.round(deliveryScoreRaw(stats)),
    breakdown: deliveryBreakdown(stats),
    tips: deliveryTips(stats),
  }
}

/** Tips are fixed per band and always quote the real number. Generated by code, not AI. */
export function deliveryTips(stats: DeliveryStats): string[] {
  const tips: string[] = []
  const wpm = Math.round(stats.wordsPerMinute)
  if (paceScore(stats.wordsPerMinute) < 75) {
    tips.push(
      stats.wordsPerMinute < 120
        ? `You spoke at about ${wpm} words per minute — that reads as hesitant. Aim for 120–160 by cutting the gaps between thoughts rather than talking faster.`
        : `You spoke at about ${wpm} words per minute — that is hard to follow. Aim for 120–160; a short breath at the end of each point helps.`,
    )
  }
  const fpm = stats.disfluencies.perMinute
  if (fillersScore(fpm) < 75) {
    tips.push(
      `You used ${stats.disfluencies.total} filler words (${fpm.toFixed(1)} per minute). Try replacing "um" with a short silent pause — silence sounds more confident than filler.`,
    )
  }
  const longest = stats.pauses.longestSec
  if (pausesScore(longest) < 75) {
    tips.push(
      `You paused ${longest.toFixed(1)}s mid-answer. A brief "let me think about that" keeps the flow natural while you gather the next point.`,
    )
  }
  if (silenceScore(stats.silenceRatio) < 75) {
    tips.push(
      `${Math.round(stats.silenceRatio * 100)}% of the recording was silence. Outline your first two points before you start speaking so there is less to search for mid-answer.`,
    )
  }
  const crutch = stats.crutches.find((c) => c.count >= 5)
  if (crutch) {
    tips.push(`You said "${crutch.phrase}" ${crutch.count} times — it may be a verbal crutch worth listening for.`)
  }
  return tips
}

function round(value: number, places = 1): number {
  const factor = 10 ** places
  return Math.round(value * factor) / factor
}

/**
 * §16 — several clips for one answer: sum the totals, recompute the rates from
 * the sums, take the max of longestSec. Averaging per-clip rates would give a
 * 6-second clip the same weight as a 90-second one.
 */
export function mergeDeliveryStats(clips: DeliveryStats[]): DeliveryStats | null {
  if (clips.length === 0) return null
  if (clips.length === 1) return clips[0]

  const durationSec = clips.reduce((s, c) => s + c.durationSec, 0)
  const speakingSec = clips.reduce((s, c) => s + c.speakingSec, 0)
  const wordCount = clips.reduce((s, c) => s + c.wordCount, 0)
  const tokenCount = clips.reduce((s, c) => s + c.tokenCount, 0)
  const disfluencyTotal = clips.reduce((s, c) => s + c.disfluencies.total, 0)
  const pauseCount = clips.reduce((s, c) => s + c.pauses.count, 0)
  const pauseTotalSec = clips.reduce((s, c) => s + c.pauses.totalSec, 0)

  const perMinute = (count: number, seconds: number) =>
    seconds > 0 ? round((count / seconds) * 60) : 0

  const sumCounts = (lists: Array<Array<{ count: number } & Record<string, unknown>>>, key: 'word' | 'phrase') => {
    const map = new Map<string, number>()
    for (const list of lists) {
      for (const item of list) {
        const k = String(item[key])
        map.set(k, (map.get(k) ?? 0) + item.count)
      }
    }
    return [...map.entries()].sort((a, b) => b[1] - a[1])
  }

  return {
    durationSec: round(durationSec),
    speakingSec: round(speakingSec),
    wordCount,
    tokenCount,
    wordsPerMinute: perMinute(wordCount, durationSec),
    articulationRate: perMinute(wordCount, speakingSec),
    disfluencies: {
      total: disfluencyTotal,
      perMinute: perMinute(disfluencyTotal, durationSec),
      breakdown: sumCounts(clips.map((c) => c.disfluencies.breakdown), 'word').map(([word, count]) => ({ word, count })),
    },
    crutches: sumCounts(clips.map((c) => c.crutches), 'phrase').map(([phrase, count]) => ({ phrase, count })),
    pauses: {
      count: pauseCount,
      totalSec: round(pauseTotalSec),
      longestSec: round(clips.reduce((m, c) => Math.max(m, c.pauses.longestSec), 0)),
      averageSec: pauseCount > 0 ? round(pauseTotalSec / pauseCount) : 0,
      byTier: {
        short: clips.reduce((s, c) => s + c.pauses.byTier.short, 0),
        medium: clips.reduce((s, c) => s + c.pauses.byTier.medium, 0),
        long: clips.reduce((s, c) => s + c.pauses.byTier.long, 0),
      },
    },
    silenceRatio: durationSec > 0 ? round(pauseTotalSec / durationSec, 3) : 0,
  }
}
